"""AI 가 뽑은 자유 문구 상품명을 RoseWeb 상품 마스터의 이름으로 맞춘다.

주문의 상품명("장미꽃다발")과 RoseWeb 마스터의 이름("꽃다발")은 다르다. 그런데
**마스터에 없는 말로 검색한 뒤 '선택'을 누르면 RoseWeb 이 죽는다**
(`Access violation at address 00000000`, 실측). 결과 목록은 UIA 에 안 보여서 누르기
전에 결과 유무를 확인할 방법도 없다.

그래서 검색어는 **반드시 마스터에 있는 이름**만 쓴다. 여기서 그 변환을 한다.
못 맞추면 '기타'(사장님 결정) — 그러면 코드는 ZZ-01 로 잡히고, 진짜 상품명은
automator 가 상품명 칸에 원문 그대로 써 넣는다.

⚠️ 마스터는 꽃집마다 다르다. 지금 값은 이 꽃집(테스트꽃집) 실측이다. 다른 꽃집을
붙일 때는 그 집 마스터를 보고 여기를 맞춰야 한다.
"""

from __future__ import annotations

# 이 꽃집 상품 마스터에서 실측한 이름들(2026-07-24). 규칙이 내놓는 값은 전부 이 안에 있어야 한다.
MASTER_TERMS: frozenset[str] = frozenset({
    "동양란", "서양란", "관엽식물", "근조3단화환", "축하3단화환",
    "꽃바구니", "플라워케이스", "꽃다발", "제단용근조바구니",
    "카네이션+꽃바구니", "케익+바구니", "샴페인+꽃바구니",
    "샴페인+케익+꽃바구니", "과일+꽃바구니", "초코렛+꽃바구니", "캔디+꽃바구니",
    "기타",
})

FALLBACK_TERM = "기타"

# 위에서부터 먼저 맞는 것을 택한다. 순서가 곧 우선순위다
# ('근조'가 '화환'보다, '동양란'이 '란'보다, '꽃다발'이 '꽃'보다 먼저 와야 한다).
_RULES: tuple[tuple[tuple[str, ...], str], ...] = (
    (("근조", "조화", "장례", "부고"), "근조3단화환"),
    (("축하", "개업", "취임", "승진", "화환"), "축하3단화환"),
    (("동양란", "동양"), "동양란"),
    (("서양란", "서양", "호접", "심비디움"), "서양란"),
    (("관엽", "화분", "식물", "선인장"), "관엽식물"),
    (("과일",), "과일+꽃바구니"),
    (("카네이션",), "카네이션+꽃바구니"),
    (("꽃다발", "부케"), "꽃다발"),
    (("꽃바구니", "바구니"), "꽃바구니"),
)


def resolve_search_term(product_name: str | None) -> str:
    """상품명 → 마스터 검색어. 못 맞추면 '기타'."""
    name = (product_name or "").strip()
    if not name:
        return FALLBACK_TERM
    for keywords, term in _RULES:
        if any(k in name for k in keywords):
            return term
    return FALLBACK_TERM
